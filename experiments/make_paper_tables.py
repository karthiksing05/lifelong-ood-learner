def load():
    with open(os.path.join(RESULTS, "aggregate.json")) as fh:
        return json.load(fh)


# Which direction is "best" for each metric.  A metric absent from BOTH sets is deliberately NOT
# ranked -- marking a winner requires knowing what winning means, and for these it is not a maximum:
# `vendi`, `diversity` and `content_ratio` are best when they MATCH real data (this repository's own
# reading, §11c: our 1.068 against real 1.007 is good, and higher would not be better), and
# `novelty` likewise.  Silently bolding their maximum would assert a claim the metrics do not make.
HIGHER_BETTER = {
    "ACC", "A", "REM", "SSS", "MS", "BWT", "joint", "digit", "fg", "bg", "f1", "F1", "recall",
    "precision", "accuracy", "auroc", "retention_exact", "both", "mean_attr", "pair", "target",
    "native", "coverage", "density", "alone_fg", "alone_bg", "alone_digit",
    "vocab_free_route_accuracy", "combination_free_route_accuracy",
}
LOWER_BETTER = {
    "FGT", "drift", "params", "wall_seconds", "memorized", "tv_ratio", "gen_rmse",
    "vocab_sent_to_free", "combination_sent_to_weights", "base_drift",
    "stored_images", "n_nodes", "final_bytes", "bytes_per_concept",
}
# Rows that are references, not competitors: a ceiling winning its own table says nothing.
def _is_reference(arm):
    a = arm.lower()
    return a.startswith("real") or "ceiling" in a or "oracle" in a


def _fmt(s, prec):
    if not isinstance(s, dict) or s.get("mean") is None:
        return "--"
    out = f"{s['mean']:.{prec}f}"
    if s.get("n", 1) > 1 and s.get("se") is not None:
        out += f" ± {s['se']:.{prec}f}"
    return out


def cell(tbl, arm, key, prec=3, rank=None):
    """Formatted cell.  `rank` = (best_value, second_value) or None to leave it unmarked."""
    out = _fmt(tbl.get(arm, {}).get(key), prec)
    if rank is None or out == "--" or _is_reference(arm):
        return out
    v = tbl[arm][key]["mean"]
    best, second = rank
    if best is not None and v == best:
        return f"**{out}**"
    if second is not None and v == second:
        return f"<u>{out}</u>"
    return out


def ranks(tbl, arms, key):
    """(best, second) among NON-reference arms, or None if the metric has no agreed direction."""
    if key not in HIGHER_BETTER and key not in LOWER_BETTER:
        return None
    vals = []
    for a in arms:
        s = tbl.get(a, {}).get(key)
        if isinstance(s, dict) and s.get("mean") is not None and not _is_reference(a):
            vals.append(s["mean"])
    if not vals:
        return None
    # rank DISTINCT values, so a tie for first shares the bold and second is the next value down
    uniq = sorted(set(vals), reverse=(key in HIGHER_BETTER))
    return (uniq[0], uniq[1] if len(uniq) > 1 else None)


def nseeds(A, name):
    return A.get(name, {}).get("n_seeds", 0)


def table(A, name, arms, keys, headers=None, prec=3, label=None, note=None):
    t = A.get(name, {}).get("table", {})
    if not t:
        return
    print(f"\n### {label or name}  *(n = {nseeds(A, name)} seeds)*\n")
    hs = headers or keys
    print("| method | " + " | ".join(hs) + " |")
    print("|---" * (len(hs) + 1) + "|")
    rk = {k: ranks(t, arms, k) for k in keys}
    for a in arms:
        if a not in t:
            continue
        print(f"| `{a}` | " + " | ".join(cell(t, a, k, prec, rk[k]) for k in keys) + " |")
    if note:
        print(f"\n{note}")


