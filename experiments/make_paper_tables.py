"""Every table in the paper, emitted as markdown from `results/aggregate.json`.

One command, no GPU:  python experiments/make_paper_tables.py > TABLES.md

The point of generating rather than typing them is that a number in the paper and a number in the
results can never drift apart, and a table can never quietly become stale after a re-run.  Every cell
carries mean +/- standard error over seeds, and the seed count is printed with each table so a
single-seed row cannot be mistaken for a pooled one.
"""
