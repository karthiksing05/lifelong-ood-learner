          ["joint", "bg", "f1", "recall"],
          ["accuracy (joint)", "the new factor", "F1", "recall"],
          label="ColorMNIST — one shared direction (1024 bytes) vs one adapter per concept (551K)",
          note="`UNSEEN combo` scores the same as `train combo`, which is what makes it a basis "
