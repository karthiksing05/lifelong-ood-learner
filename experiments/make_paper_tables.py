"""Every table in the paper, emitted as markdown from `results/aggregate.json`.

One command, no GPU:  python experiments/make_paper_tables.py > TABLES.md

The point of generating rather than typing them is that a number in the paper and a number in the
results can never drift apart, and a table can never quietly become stale after a re-run.  Every cell
carries mean +/- standard error over seeds, and the seed count is printed with each table so a
single-seed row cannot be mistaken for a pooled one.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import RESULTS                                              # noqa: E402


def load():
    with open(os.path.join(RESULTS, "aggregate.json")) as fh:
        return json.load(fh)


def cell(tbl, arm, key, prec=3):
    s = tbl.get(arm, {}).get(key)
    if not isinstance(s, dict) or s.get("mean") is None:
        return "--"
    out = f"{s['mean']:.{prec}f}"
    if s.get("n", 1) > 1 and s.get("se") is not None:
        out += f" ± {s['se']:.{prec}f}"
    return out


def nseeds(A, name):
    return A.get(name, {}).get("n_seeds", 0)


def table(A, name, arms, keys, headers=None, prec=3, label=None, note=None):
    t = A.get(name, {}).get("table", {})
    if not t:
        return
    print(f"\n### {label or name}  *(n = {nseeds(A, name)} seeds)*\n")
    hs = headers or keys
    print("| method | " + " | ".join(hs) + " |")
    print("|---" * (len(hs) + 1) + "|")
    for a in arms:
        if a not in t:
            continue
        print(f"| `{a}` | " + " | ".join(cell(t, a, k, prec) for k in keys) + " |")
    if note:
        print(f"\n{note}")


def main():
    A = load()
    print("# Tables\n")
    print("Generated by `python experiments/make_paper_tables.py` from `results/aggregate.json`.")
    print("Every cell is mean ± standard error over seeds; `--` means the arm was not run in that")
    print("experiment. Do not edit by hand -- regenerate.")

    print("\n---\n\n## 1. Composition: does it recover a combination never observed?")
    table(A, "n9_showdown",
          ["real", "ours", "poe-guided", "inversion", "nearest-class"],
          ["joint", "recall", "f1", "content_ratio"],
          ["accuracy (joint)", "recall", "F1", "content diversity"],
          label="ColorMNIST — held-out (digit, fg, bg) slots",
          note="`real` is held-out images, the ceiling. `poe-guided` is the published method: it "
               "scores *higher* accuracy than ours and F1 ~0 because it emits near-copies of the "
               "query.")
    table(A, "n20_celeba_composition_pair",
          ["real", "ours", "poe-guided", "query-only", "nearest-class"],
          ["pair", "target", "recall", "f1", "content_ratio"],
          ["pair (both, never co-occurred)", "target attr", "recall", "F1", "content diversity"],
          label="CelebA — `Smiling` x `Big_Nose` never co-occur in training",
          note="`pair` = both withheld attributes correct at once. `nearest-class` cannot express "
               "the co-occurrence by construction: every trained neighbour differs on at least one "
               "of the two.")
    table(A, "n20_celeba_composition",
          ["real", "ours", "poe-guided", "query-only", "nearest-class"],
          ["target", "joint", "mean_attr", "recall", "f1"],
          ["target attr", "joint", "mean attribute", "recall", "F1"],
          label="CelebA — 24 whole combinations withheld (the weaker split)")

    print("\n---\n\n## 2. The routing rule: what a new combination costs, and what a new value costs")
    table(A, "n11_basis_extension_nmadapt",
          ["real (ceiling)", "train combo", "UNSEEN combo", "adapter (per concept)",
           "adapter on REAL images"],
          ["joint", "bg", "f1", "recall"],
          ["accuracy (joint)", "the new factor", "F1", "recall"],
          label="ColorMNIST — one shared direction (1024 bytes) vs one adapter per concept (551K)",
          note="`UNSEEN combo` scores the same as `train combo`, which is what makes it a basis "
               "rather than a lookup. Norm-matching the new direction is required; without it F1 "
               "swings 0.65 / 0.35 / 0.71 across seeds.")
    table(A, "n21_celeba_vocabulary_Gray_Hair",
          ["real (ceiling) [UNSEEN]", "adapter (real) [UNSEEN]", "learned value [UNSEEN]",
           "untrained value [UNSEEN]"],
          ["target", "mean_attr", "recall", "f1"],
          ["the withheld attribute", "mean attribute", "recall", "F1"],
          label="CelebA — an attribute whose ON value the backbone NEVER saw",
          note="The learned conditioning vector is **not separated** from the untrained one; only a "
               "weight update from real images recovers the attribute. Absolute values are "
               "compressed because this attribute's probe has TPR 0.32, which is why the ceiling "
               "row is reported beside every arm.")

    print("\n---\n\n## 3. Preservation and forgetting")
    table(A, "n5_classinc",
          ["ours", "independent", "ttt", "ewc", "finetune", "replay"],
          ["ACC", "FGT", "retention_exact", "params"],
          ["accuracy", "forgetting (0 = none)", "fraction bit-identical", "adapter params"],
          label="ColorMNIST — Split-ColorMNIST class-incremental, REAL held-out images",
          note="Arms that structurally *remove* shared parameters sit at exactly 0.000; arms that "
               "try to *protect* them forget.")
    table(A, "n22_celeba_lifelong",
          ["ours", "independent", "finetune", "replay", "ewc"],
          ["ACC", "FGT", "retention_exact", "params"],
          ["mean-attribute accuracy", "forgetting", "fraction bit-identical", "adapter params"],
          label="CelebA — class-incremental over held-out combinations, REAL images")

    print("\n---\n\n## 4. Native parity: against a backbone TRAINED on the held-out slot")
    table(A, "n23_native_parity", ["real", "native", "ours", "paper"],
          ["joint", "f1", "recall", "content_ratio"],
          ["accuracy (joint)", "F1", "recall", "content diversity"],
          label="ColorMNIST — the oracle is trained on all 160 slots")
    p = A.get("n23_native_parity", {}).get("parity", {})
    if p:
        print("\n**Parity (consolidated / native):**\n")
        print("| method | accuracy | F1 | recall |")
        print("|---|---|---|---|")
        for a in ("ours", "paper"):
            row = p.get(a, {})
            print(f"| `{a}` | " + " | ".join(
                (f"{row[k]['mean']:.3f} ± {row[k].get('se', 0):.3f}" if k in row else "--")
                for k in ("joint", "f1", "recall")) + " |")
        print("\nA consolidated concept reaches most of native-level *coverage* at zero retraining "
              "and does not reach native per-sample *precision*; the published per-query LoRA "
              "reaches neither.")

    print("\n---\n\n## 5. The router: the system deciding its own updates")
    r = A.get("n18_router", {}).get("table", {})
    if r:
        print(f"\n### Detection *(n = {nseeds(A, 'n18_router')} seeds)*\n")
        print("| decision | AUROC | unconditional ablation |")
        print("|---|---|---|")
        for k in ("novel vs in-distribution", "new-vocabulary vs new-combination"):
            row = r.get(k, {})
            a = row.get("auroc", {}); b = row.get("uncond", {})
            fmt = lambda s: (f"{s['mean']:.3f} ± {s.get('se', 0):.3f}" if s else "--")
            print(f"| {k} | {fmt(a)} | {fmt(b)} |")
        def stat_cell(key):
            s = r.get(key)
            if not isinstance(s, dict) or s.get("mean") is None:
                return "--"
            out = f"{s['mean']:.3f}"
            return out + (f" ± {s['se']:.3f}" if s.get("n", 1) > 1 else "")

        print("\n| quantity | value |\n|---|---|")
        for k, lab in (("accuracy", "self-routing accuracy"),
                       ("vocab_sent_to_free", "new vocabulary sent down the FREE route"),
                       ("combination_sent_to_weights", "new combination sent to the WEIGHT route"),
                       ("vocab_free_route_accuracy",
                        "quality if a vocabulary item takes the free route"),
                       ("combination_free_route_accuracy",
                        "quality where the free route is correct")):
            print(f"| {lab} | {stat_cell(k)} |")
        print("\nThe error is one-sided in the safe direction: a new vocabulary item was never once "
              "routed to the free path, while some new combinations over-spend on an adapter they "
              "did not need. The unconditional ablation matches the conditional signal, so this is "
              "a density-based novelty detector and NOT evidence that the factor basis decides.")

    print("\n---\n\n## 6. Discovery is free (analytic track)")
    table(A, "e2_composition", ["poe_tree", "poe_ascent", "query_only", "top1", "top3"],
          ["joint", "novelty", "diversity"],
          ["accuracy (joint)", "novelty", "diversity"],
          label="ColorMNIST — a Cobweb tree's nodes vs the paper's mode ascent",
          note="`poe_tree` (tree nodes read as concepts, closed form) matches `poe_ascent` (gradient "
               "ascent on the score field) within error, so concept discovery costs nothing. "
               "`query_only` scores high accuracy at a third the novelty and diversity -- copying "
               "again.")


if __name__ == "__main__":
    main()
