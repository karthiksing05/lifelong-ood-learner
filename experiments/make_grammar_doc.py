"""docs/GRAMMAR.md from results/robot/grammar_readout.json (experiments/grammar_readout.py), c1_grammar.json and the phase-outcome
reads (experiments/phase_outcomes.py --json): the prototypes and the grammar read out, every number from those files.

    python experiments/make_grammar_doc.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results", "robot")
EXAMPLES = (48, 58, 32, 3, 13, 16, 40, 73, 39)
TYPES = ("black_book", "chefmate_8_frypan", "akita_black_bowl", "ketchup")


def main():
    g = json.load(open(os.path.join(R, "grammar_readout.json")))
    c1 = json.load(open(os.path.join(R, "c1_grammar.json")))["levels"]
    L = []
    w = L.append
    w("# Grammar x bindings, read out")
    w("")
    w("Generated by `experiments/make_grammar_doc.py` from `results/robot/grammar_readout.json` (`experiments/grammar_readout.py`), "
      "`c1_grammar.json` and the phase-outcome reads; the method is in [METHOD.md](METHOD.md). Every task is read from its ONE demo "
      f"({len(g['tasks'])} LIBERO-90 tasks), labelled by the 40-task prototype hierarchy (r19's basin rule) and cut into phases by rules v2.")
    w("")
    w("## 1. The alphabet: coarse prototypes are shared verbs")
    w("")
    p55 = sorted(g["prototypes"]["0.55"].items(), key=lambda kv: -kv[1]["frames"])
    w(f"At t = 0.55 the hierarchy has {len(p55)} prototypes; each is named by what its frames do (gripper state, hand speed and vertical "
      "motion, and the rules-v2 phase its frames fall in):")
    w("")
    w("| prototype | name | frames | tasks | speed (cm/step) | vertical (cm/step) |")
    w("|---|---|---|---|---|---|")
    for c, v in p55:
        w(f"| {c} | {v['name']} | {v['frames']} | {v['tasks']} | {v['speed_cm_per_step']:.2f} | {v['dz_cm_per_step']:+.2f} |")
    lv = c1["0.55"]
    w("")
    w(f"Its label changes where the phases change (C1): {lv['change_points_per_demo']:.1f} change points per demo; recall of the phase "
      f"events {lv['recall']:.2f} (random {lv['random_recall']:.2f}), precision {lv['precision']:.2f} (random {lv['random_precision']:.2f}).")
    p4 = sorted(g["prototypes"]["0.4"].items(), key=lambda kv: -kv[1]["tasks"])
    w("")
    w(f"At t = 0.4 the demos use {len(p4)} prototypes; the ones most tasks share:")
    w("")
    w("| prototype | name | tasks | frames | vertical (cm/step) |")
    w("|---|---|---|---|---|")
    for c, v in p4[:12]:
        w(f"| {c} | {v['name']} | {v['tasks']} | {v['frames']} | {v['dz_cm_per_step']:+.2f} |")
    w("")
    w("## 2. Programs as sentences")
    w("")
    fam = g["families"]
    w("A program is its phases, each anchored on an object, with the bindings in readable units: the grasp as the hand's position in "
      "the object's frame at the close, the place as the object's release position in the receptacle's frame. Grammars across the "
      "tasks: " + ", ".join(f"{k.replace(' ', ' -> ')} {len(v)}" for k, v in sorted(fam.items(), key=lambda kv: -len(kv[1]))) + ".")
    w("")
    w("| task | instruction | program | bytes |")
    w("|---|---|---|---|")
    for t in EXAMPLES:
        p = g["programs"].get(str(t))
        if p:
            w(f"| {t} | {p['language']} | {p['sentence']} | {p['bytes']:,} |")
    w("")
    w("## 3. What the prototypes carry and what the bindings carry")
    w("")
    sk, go = g["string_by_key"], g["grasp_offset_cm"]
    w("Distances between tasks' phases, grouped by the binding table's keys (grasp: object type; place: the goal relation), with a "
      "permutation test that shuffles the keys across phases:")
    w("")
    w("| what | same key | other key | permutation p |")
    w("|---|---|---|---|")
    w(f"| carry: prototype string (edit distance, t = 0.4) | {sk['carry']['same_key_median']:.2f} | {sk['carry']['other_key_median']:.2f} | "
      f"{sk['carry']['perm_p']:.3f} |")
    w(f"| grasp: prototype string (edit distance, t = 0.4) | {sk['grasp']['same_key_median']:.2f} | {sk['grasp']['other_key_median']:.2f} | "
      f"{sk['grasp']['perm_p']:.2f} |")
    w(f"| grasp: binding geometry (cm) | {go['within_type_median']:.1f} | {go['across_type_median']:.1f} | {g['grasp_geometry_perm_p']:.4f} |")
    w("")
    w("The carry's prototype string encodes the place relation; the grasp's motion is shared by every object and its object-specific part "
      "is the binding's geometry. These are the keys the binding table uses (grasp sources by object type, place sources by goal relation).")
    w("")
    w("| object type | tasks | hand in the object's frame (cm) | approach |")
    w("|---|---|---|---|")
    for ty in TYPES:
        for x in g["grasp_by_type"].get(ty, []):
            w(f"| {ty} | {x['task']} | {x['hand_in_object_cm']} | {x['approach']} |")
    po = os.path.join(R, "phase_outcomes_dev.json")
    if os.path.exists(po):
        d = json.load(open(po))
        w("")
        w("## 4. Where programs fail, by phase")
        w("")
        w(d.get("caption", ""))
        w("")
        w("| arm | episodes | failed: reach | lift | bring | place | success |")
        w("|---|---|---|---|---|---|---|")
        for arm, v in d["arms"].items():
            t = v["total"]
            n = sum(t.values())
            w(f"| {arm} | {n} | {t['reach']} | {t['lift']} | {t['bring']} | {t['place']} | {t['success']} |")
    open(os.path.join(ROOT, "docs", "GRAMMAR.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("docs/GRAMMAR.md written")


if __name__ == "__main__":
    main()
