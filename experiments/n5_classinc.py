"""N5 — Split-ColorMNIST class-incremental, our method against the standard CL baselines.

N3/N4 stream *composed* concepts: the pool is generated by the PoE teacher.  This experiment streams
**real held-out images** instead, one batch of classes at a time, which is the canonical
class-incremental protocol (Split-MNIST / Split-CIFAR in the continual-learning literature, here on
the 40 held-out ColorMNIST compositions the backbone has never seen).  It answers a question the
composition experiments cannot: *can this thing absorb batches of genuinely new instances?*

It also gives the comparison a recognisable frame.  Every arm below is a named method from the CL
literature, implemented as a configuration of the same adapter bank, so the differences are the
mechanism and nothing else:

  `finetune`     one shared adapter trained on each incoming batch in sequence.  The classic
                 catastrophic-forgetting control (flat topology, ancestors trainable).
  `replay`       finetune + GENERATIVE REPLAY (Shin et al. 2017): before absorbing batch t, sample
                 from every concept already learned and mix those samples into the objective.  The
                 standard strong baseline, and unusually natural here because every consolidated
                 concept is itself a sampler -- no stored exemplars are needed.
  `independent`  one private adapter per task, nothing shared (parameter isolation).  This is also
                 exactly the poe-diffusion paper's per-query LoRA, kept rather than discarded.
  `ours`         hierarchical adapters with frozen ancestors and batch addition.

Metrics are the standard ones, computed from the full accuracy matrix acc[i][t]:
  ACC  mean final accuracy   BWT  backward transfer (0 = no forgetting)   FGT  forgetting measure
plus adapter parameters, wall clock, and the fraction of concepts still bit-identical to birth.
"""
import argparse
import os
import sys
import time

import numpy as np
import torch

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import CACHE, RESULTS, ood_queries                         # noqa: E402
from n4_batch import (cl_metrics, efficiency_metrics,                  # noqa: E402
                      quality_metrics)

from lifelong_ood.data.datasets import load_colormnist                      # noqa: E402
from lifelong_ood.evals import (composition_accuracy, fit_probes, frechet_distance,  # noqa: E402
                                save_grid, save_json)
from lifelong_ood.neural import (NeuralLifelongLearner, fingerprint, load_field,  # noqa: E402
                                 to_data, to_model)
from lifelong_ood.neural.baselines import (CLoRA, DERPlusPlus, EWC, MAS, SI,   # noqa: E402
                                           test_time_train)

# arm -> (flat topology, freeze ancestors, generative replay, EWC, test-time only)
#
# The regularization arms (ewc/si/mas/c-lora) and the rehearsal arms (replay/gen-distill/der++) all
# run on the SAME flat topology with trainable shared parameters, so the only difference between them
# is the protection mechanism.  `ours` and `independent` change the topology instead, which is the
# axis the whole table is about: protecting shared weights versus not sharing them.
ARMS = {
    "ours":        (False, True,  False, False, False),
    "independent": (True,  True,  False, False, False),
    "finetune":    (True,  False, False, False, False),
    "replay":      (True,  False, True,  False, False),
    "gen-distill": (True,  False, True,  False, False),
    "der++":       (True,  False, False, False, False),
    "ewc":         (True,  False, False, True,  False),
    "si":          (True,  False, False, False, False),
    "mas":         (True,  False, False, False, False),
    "ttt":         (True,  False, False, False, True),
    "c-lora":      (True,  False, False, False, False),
}
# arms whose protection is a penalty sharing the (begin_task, penalty, consolidate) hook
REGULARIZERS = {"ewc": EWC, "si": SI, "mas": MAS, "c-lora": CLoRA}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--ckpt", default=os.path.join(CACHE, "ddpm_colormnist.pt"))
    p.add_argument("--n-tasks", type=int, default=12)
    p.add_argument("--batch-size", type=int, default=3, help="tasks arriving together")
    p.add_argument("--n-train", type=int, default=64, help="REAL images per task")
    p.add_argument("--n-samples", type=int, default=16)
    p.add_argument("--n-per-slot", type=int, default=100)
    p.add_argument("--epochs", type=int, default=40)
    p.add_argument("--rank", type=int, default=8)
    p.add_argument("--replay-n", type=int, default=32)
    p.add_argument("--steps", type=int, default=50)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--arms", nargs="+", default=list(ARMS))
    p.add_argument("--ewc-lambda", type=float, default=5000.0)
    p.add_argument("--clora-lambda", type=float, default=1e4,
                   help="C-LoRA self-regularisation strength (Smith et al., TMLR 2024)")
    p.add_argument("--si-lambda", type=float, default=1.0,
                   help="SI penalty strength c (Zenke et al. 2017; paper uses 1.0)")
    p.add_argument("--mas-lambda", type=float, default=1.0,
                   help="MAS penalty strength (Aljundi et al. 2018; untuned default 1.0)")
    p.add_argument("--buffer-size", type=int, default=200,
                   help="DER++ exemplar buffer (Buzzega et al. report 200/500/5120)")
    p.add_argument("--der-alpha", type=float, default=0.5, help="DER++ dark-knowledge weight")
    p.add_argument("--der-beta", type=float, default=0.5, help="DER++ replay weight")
    p.add_argument("--tag", default="", help="suffix for the output file; --quick runs force one "
                                             "so a smoke can never overwrite a full result")
    p.add_argument("--quick", action="store_true")
    args = p.parse_args()
    if args.quick:
        args.tag = args.tag or "_smoke"
        args.n_tasks, args.batch_size, args.n_train = 4, 2, 24
        args.n_samples, args.n_per_slot, args.epochs = 8, 20, 4
        args.replay_n, args.steps = 8, 10
    dev = "cuda" if torch.cuda.is_available() else "cpu"

    data = load_colormnist(n_per_slot=args.n_per_slot, seed=args.seed)
    probes = fit_probes(data, seed=args.seed, epochs=8 if args.quick else 30)
    qs = ood_queries(data, n_slots=args.n_tasks, seed=args.seed)
    # each task = a batch of REAL held-out images of one unseen composition
    tasks = []
    for q in qs:
        idx = np.concatenate([[q["query"]], q["rest"]])[:args.n_train]
        tasks.append(dict(name=f"task_{q['slot']}", q=q, X=to_model(data["X"][idx]),
                          R=data["X"][idx].astype(np.float32)))
    print(f"[n5] {len(tasks)} tasks x {args.n_train} REAL images, batches of {args.batch_size}, "
          f"arms {args.arms}, device {dev}", flush=True)
    save_grid(data["X"][np.concatenate([[t['q']['query']] for t in tasks[:8]])],
              os.path.join(RESULTS, "n5_stream.png"), ncol=8,
              title="the incremental stream: one real image from each of the first 8 tasks")

    rows = []
    for arm in args.arms:
        flat, freeze, use_replay, use_ewc, is_ttt = ARMS[arm]
        field = load_field(args.ckpt, device=dev)
        L = NeuralLifelongLearner(field, rank=args.rank, steps=args.steps, seed=args.seed,
                                  device=dev, flat=flat, freeze_ancestors=freeze)
        # every regularizer shares EWC's (begin_task, penalty, consolidate) interface, so they all
        # ride the same hook and differ only in how importance is estimated
        ewc = None
        if arm in REGULARIZERS:
            lam = {"ewc": args.ewc_lambda, "c-lora": args.clora_lambda,
                   "si": args.si_lambda, "mas": args.mas_lambda}[arm]
            ewc = REGULARIZERS[arm](lam=lam)
        buffer = (DERPlusPlus(size=args.buffer_size, alpha=args.der_alpha, beta=args.der_beta,
                              seed=args.seed) if arm == "der++" else None)
        acc_rows = {t["name"]: [] for t in tasks}
        fd_rows = {t["name"]: [] for t in tasks}
        refs = {t["name"]: t["R"] for t in tasks}
        marks, learned = {}, []
        params_curve = []
        t0 = time.time()
        for i0 in range(0, len(tasks), args.batch_size):
            grp = tasks[i0:i0 + args.batch_size]
            replay = None
            if use_replay and learned:
                # sample from the model's OWN earlier concepts -- no stored data
                replay = [(nm, L.sample_concept(nm, n=args.replay_n, seed=args.seed + 900))
                          for nm, _ in learned]
            # TTT keeps NO cross-task state, so the stream only REGISTERS each concept (epochs=0
            # leaves the adapter at its zero-initialized no-op); all fitting happens at eval time
            # and is undone afterwards.  Training here as well would make it finetune+TTT, not TTT.
            L.consolidate_batch([(t["name"], t["X"], None) for t in grp],
                                epochs=(0 if is_ttt else args.epochs),
                                replay=replay, ewc=ewc, buffer=buffer,
                                replay_distill=(arm == "gen-distill"))
            for t in grp:
                learned.append((t["name"], t["q"]))
                marks[t["name"]] = fingerprint(field, t["name"], seed=args.seed)
            for si, (nm, q) in enumerate(learned):
                if is_ttt:
                    # test-time training keeps NO cross-task state: re-fit this task from its own
                    # data at evaluation time and throw the adapter away afterwards.  It therefore
                    # cannot forget -- and cannot accumulate -- which is exactly what makes it the
                    # control for whether retention is doing any work.
                    tk = next(t for t in tasks if t["name"] == nm)
                    restore = test_time_train(L, tk["X"], nm, epochs=args.epochs, seed=args.seed)
                    S = to_data(L.sample_concept(nm, n=args.n_samples,
                                                 seed=args.seed + 500 + si)).astype(np.float32)
                    restore()
                else:
                    S = to_data(L.sample_concept(nm, n=args.n_samples,
                                                 seed=args.seed + 500 + si)).astype(np.float32)
                acc_rows[nm].append(composition_accuracy(probes, S, q["d"], q["f"], q["b"])["joint"])
            # probe accuracy is fidelity-blind -- an arm can keep the attributes legible while
            # its images degrade -- so track generation quality on the same schedule
            fd_rows[nm].append(frechet_distance(S, refs[nm]))
            params_curve.append(L.bank.n_params())
            exact = float(np.mean([float(np.array_equal(fingerprint(field, nm, seed=args.seed),
                                                        marks[nm])) for nm, _ in learned]))
            print(f"[n5:{arm}] {len(learned)}/{len(tasks)} tasks: "
                  f"mean acc {np.mean([acc_rows[nm][-1] for nm, _ in learned]):.2f}, "
                  f"exact {exact:.2f}, {L.bank.n_params() / 1e6:.2f}M, "
                  f"{time.time() - t0:.0f}s", flush=True)
        acc = [acc_rows[t["name"]] for t in tasks if acc_rows[t["name"]]]
        fd = [fd_rows[t["name"]] for t in tasks if fd_rows[t["name"]]]
        m = cl_metrics(acc)
        qm = quality_metrics(fd, lower_better=True)
        # What each arm has to KEEP, which the accuracy columns hide.  Diaz-Rodriguez et al. (2018)
        # formalize this as SSS; the raw count is more legible and makes the same point: DER++ buys
        # its retention with a permanent buffer of real images and TTT keeps every task's data
        # forever, where the frozen-ancestor bank and every regularizer store none.
        stored = (len(buffer) if buffer is not None else
                  (sum(len(t["X"]) for t in tasks) if is_ttt else 0))
        em = efficiency_metrics(acc, params_curve or [L.bank.n_params()], stored,
                                sum(len(t["X"]) for t in tasks))
        rows.append(dict(arm=arm, wall_seconds=time.time() - t0, params=L.bank.n_params(),
                         retention_exact=exact, acc_matrix=acc, stored_images=stored,
                         fd_matrix=fd, params_curve=params_curve,
                         **{f"q{k}": v for k, v in qm.items()}, **em, **m))
        print(f"[n5] -> {arm}: ACC {m['ACC']:.3f}, BWT {m['BWT']:+.3f}, FGT {m['FGT']:.3f}\n",
              flush=True)

    save_json(dict(rows=rows, config=vars(args)),
              os.path.join(RESULTS, f"n5_classinc{args.tag}.json"), seed=args.seed)
    print(f"\n[n5] Split-ColorMNIST class-incremental, {args.n_tasks} tasks of real held-out images")
    print(f"    {'arm':13s}{'ACC':>7s}{'BWT':>9s}{'FGT':>8s}{'exact':>8s}"
          f"{'AFQ':>8s}{'FR':>8s}{'params':>9s}{'stored':>8s}{'wall(s)':>9s}")
    for r in rows:
        print(f"    {r['arm']:13s}{r['ACC']:7.3f}{r['BWT']:+9.3f}{r['FGT']:8.3f}"
              f"{r['retention_exact']:8.2f}{r.get('qAFQ', float('nan')):8.3f}"
              f"{r.get('qFR', float('nan')):+8.3f}{r['params'] / 1e6:8.2f}M"
              f"{r.get('stored_images', 0):8d}{r['wall_seconds']:9.0f}")
    print("\n  ACC final mean accuracy (higher better) | BWT backward transfer (0 = no forgetting)")
    print("  FGT forgetting measure (0 = none) | exact = fraction bit-identical to birth")
    print("  stored = REAL images the arm must retain forever (0 = keeps no data)")
    print("  AFQ final generation quality (Frechet to real, LOWER better) | FR its degradation")
    print(f"[n5] wrote {RESULTS}/n5_classinc{args.tag}.json")


if __name__ == "__main__":
    main()
